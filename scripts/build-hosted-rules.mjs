import {readFileSync,writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
const source=readFileSync(new URL('../server/authority.mjs',import.meta.url),'utf8');
const start=source.indexOf('export class SharedRealm {');
if(start<0)throw Error('SharedRealm source was not found.');
const helpers=source.slice(0,start).replace(/^import .* from 'node:(sqlite|fs|path)';\n/gm,'');
const methods=[...source.slice(start).matchAll(/^  ([A-Za-z]\w*)\(/gm)];
const selected=['agentToken','view','transfer','speak','dispatch'].map(name=>{
  const i=methods.findIndex(m=>m[1]===name);if(i<0)throw Error(`Missing shared method: ${name}`);
  return source.slice(start+methods[i].index,start+(methods[i+1]?.index??source.length));
}).join('');
const insert="this.db.prepare('INSERT INTO credentials VALUES(?,?,?,?,?)').run(id,hash(this.agentToken(id)),p.id,'agent',expiresAt)";
const renew="this.db.prepare('UPDATE credentials SET expires_at=? WHERE id=?').run(c.expires_at,c.id)";
if(!selected.includes(insert)||!selected.includes(renew))throw Error('Credential adapter hooks changed; review the hosted adapter.');
const body=selected.replace(insert,"this.saveCredential({id,token_hash:hash(this.agentToken(id)),player_id:p.id,role:'agent',expires_at:expiresAt})").replace(renew,'this.renewCredential(c)');
const out=`// Generated by scripts/build-hosted-rules.mjs from server/authority.mjs.\n// Source SHA-256: ${createHash('sha256').update(source).digest('hex')}\n${helpers}\nexport {genesis,assertState,canonical,hash,exact,object,plainText,integer,fail};\nexport class HostedRules {\n${body}}\n`;
const target=new URL('../server/hosted-rules.mjs',import.meta.url);
if(process.argv.includes('--check')){
 if(readFileSync(target,'utf8')!==out)throw Error('Hosted rules differ from the canonical authority.');
}else writeFileSync(target,out);
